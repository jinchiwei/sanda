"""Generate internal/ui/logo.go: 散打 as a pixel map for half-block rendering.

Each pixel is ' ' (empty), 'L' (left character), 'R' (right character) or 'O' (1-pixel outline).
Two pixel rows make one text row at runtime, so each row of the map is one pixel tall and one cell wide.

Usage: python3 scripts/gen-logo.py "$(fc-match -f '%{file}' 'Noto Sans CJK TC:bold')" 30 1.4 > internal/ui/logo.go
"""
import sys

from PIL import Image, ImageDraw, ImageFilter, ImageFont

font_path, px, stretch = sys.argv[1], int(sys.argv[2]), float(sys.argv[3])
SS = 8  # supersample, then shrink with the horizontal stretch
big = ImageFont.truetype(font_path, px * SS)
chars = "散打"
gap = px * SS // 8
masks, x = [], 0
for ch in chars:
    l, t, r, b = big.getbbox(ch)
    masks.append((ch, x - l))
    x += (r - l) + gap
_, top, _, bottom = big.getbbox(chars)
W, H = x - gap + 2 * SS, bottom - top + 2 * SS
layers = []
for ch, ox in masks:
    img = Image.new("L", (W, H), 0)
    ImageDraw.Draw(img).text((ox + SS, SS - top), ch, font=big, fill=255)
    tw, th = round(W / SS * stretch), round(H / SS)
    layers.append(img.resize((tw, th), Image.LANCZOS).point(lambda v: 255 if v > 110 else 0))
tw, th = layers[0].size
# Pad by 1 pixel so the outline fits, then dilate the union for the outline.
pad = lambda im: im.crop((-1, -1, tw + 1, th + 1))
left, right = pad(layers[0]), pad(layers[1])
union = Image.new("L", left.size, 0)
union.paste(255, mask=left)
union.paste(255, mask=right)
ring = union.filter(ImageFilter.MaxFilter(3))
W2, H2 = union.size
rows = []
for y in range(H2):
    row = ""
    for x in range(W2):
        if left.getpixel((x, y)):
            row += "L"
        elif right.getpixel((x, y)):
            row += "R"
        elif ring.getpixel((x, y)):
            row += "O"
        else:
            row += " "
    rows.append(row.rstrip())
while rows and not rows[0].strip():
    rows.pop(0)
while rows and not rows[-1].strip():
    rows.pop()
indent = min(len(r) - len(r.lstrip()) for r in rows if r.strip())
rows = [r[indent:] for r in rows]
if len(rows) % 2:
    rows.append("")

print("// Code generated by scripts/gen-logo.py; DO NOT EDIT.")
print()
print("package ui")
print()
print(f"// logoPixels is 散打 (Noto Sans CJK TC Black, {px}px, stretched {stretch}× wide): L left character,")
print("// R right character, O outline. Two rows make one text row.")
print("var logoPixels = []string{")
for r in rows:
    print(f'\t"{r}",')
print("}")
