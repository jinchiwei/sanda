"""Generate internal/ui/logo.go: 散打 rasterised with a CJK font as half-block art.

Usage: python3 scripts/gen-logo.py "$(fc-match -f '%{file}' 'Noto Sans CJK TC:black')" 26 > internal/ui/logo.go
"""
import sys

from PIL import Image, ImageDraw, ImageFont

font_path, px = sys.argv[1], int(sys.argv[2])
text = "散打"
font = ImageFont.truetype(font_path, px)
l, t, r, b = font.getbbox(text)
img = Image.new("L", (r - l + 2, b - t + 2), 0)
ImageDraw.Draw(img).text((1 - l, 1 - t), text, font=font, fill=255)
w, h = img.size


def on(x, y):
    return y < h and img.getpixel((x, y)) > 110


rows = []
for y in range(0, h + h % 2, 2):
    row = "".join("█" if on(x, y) and on(x, y + 1) else "▀" if on(x, y) else "▄" if on(x, y + 1) else " " for x in range(w))
    rows.append(row.rstrip())
while rows and not rows[0].strip():
    rows.pop(0)
while rows and not rows[-1].strip():
    rows.pop()
indent = min(len(r) - len(r.lstrip()) for r in rows if r.strip())
rows = [r[indent:] for r in rows]

print("// Code generated by scripts/gen-logo.py; DO NOT EDIT.")
print()
print("package ui")
print()
print(f"// logo is 散打 in Noto Sans CJK TC Black at {px}px, two pixel rows per text row.")
print("var logo = []string{")
for r in rows:
    print(f"\t{r!r},".replace("'", '"'))
print("}")
